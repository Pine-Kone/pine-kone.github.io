/* ====================================
   Render Collection
   ==================================== */

function renderCollection() {

  const grid = document.getElementById("card-grid");

  let obtainedCount = 0;

  grid.innerHTML = "";


  jolteonCards.forEach((card) => {

    if (card.obtained) {
      obtainedCount++;
    }


    const cardElement = document.createElement("article");

    cardElement.className =
      `tcg-card ${card.obtained ? "obtained" : "not-obtained"}`;


    const statusText =
      card.obtained
        ? "✓ Obtained"
        : "○ Still Chasing";


    const statusClass =
      card.obtained
        ? "status-obtained"
        : "status-not-obtained";


    let acquisitionHTML = "";


    if (card.obtained) {

      acquisitionHTML = `
        <div class="acquisition-info">

          <p>
            <span class="acquisition-label">
              Date:
            </span>

            ${card.obtainedDate || "Not recorded"}
          </p>

          <p>
            <span class="acquisition-label">
              Location:
            </span>

            ${card.obtainedLocation || "Not recorded"}
          </p>

        </div>
      `;
    }


    cardElement.innerHTML = `

      <div class="card-image-wrapper">

        <img
          src="${card.image}"
          alt="${card.name} — ${card.set} ${card.number}"
          loading="lazy"
          onerror="this.style.display='none'; this.nextElementSibling.style.display='block';"
        >

        <div
          class="card-image-placeholder"
          style="display: none;"
        >
          Card image not added yet.
        </div>

      </div>


      <div class="card-info">

        <h3 class="card-name">
          ${card.name}
        </h3>

        <p class="card-set">
          ${card.set}
        </p>

        <p class="card-number">
          ${card.number}
        </p>


        <span class="ownership-status ${statusClass}">
          ${statusText}
        </span>


        ${acquisitionHTML}

      </div>
    `;


    grid.appendChild(cardElement);

  });


  const totalCount = jolteonCards.length;

  const remainingCount =
    totalCount - obtainedCount;

  const completion =
    totalCount === 0
      ? 0
      : Math.round((obtainedCount / totalCount) * 100);


  document.getElementById("total-cards").textContent =
    totalCount;

  document.getElementById("obtained-cards").textContent =
    obtainedCount;

  document.getElementById("remaining-cards").textContent =
    remainingCount;

  document.getElementById("completion-percent").textContent =
    `${completion}%`;
}


/* ====================================
   Start Page
   ==================================== */

document.addEventListener(
  "DOMContentLoaded",
  renderCollection
);
